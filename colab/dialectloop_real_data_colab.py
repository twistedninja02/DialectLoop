def transcribe_audio_with_whisper(audio_path: str, model_size: str = "large-v3") -> str:
    """
    Transcribes regional Bengali speech audio using OpenAI Whisper loaded from GitHub.
    Uses language='bn' for optimal Bengali acoustic modeling.
    """
    try:
        import whisper
        print(f"Loading Whisper model '{model_size}' from GitHub (openai/whisper)...")
        model = whisper.load_model(model_size)
        res = model.transcribe(audio_path, language="bn", task="transcribe")
        return res.get("text", "").strip()
    except Exception as e:
        print(f"Note: Whisper local inference skipped ({e}). Using pre-computed ASR transcripts.")
        return ""

